"""
User-facing evidence report for a case-specific answer. Built only from data the pipeline actually produced
(retrieved chunks, judge verdicts, retrieval assessment); nothing here is generated by a model, so a page, filename
or excerpt can never be invented.

Claim labels shown to users: Supported / Partially Supported / Contradicted / Unverified
(the judge's NOT_VERIFIABLE is presented as "Unverified").
"""
import re

from ai_core.guardrails.output_guard import redact_pii
from ai_core.rag.provenance import paragraph_numbers

LABELS = {
    "SUPPORTED": "Supported",
    "PARTIALLY_SUPPORTED": "Partially Supported",
    "CONTRADICTED": "Contradicted",
    "NOT_VERIFIABLE": "Unverified",
}
EXCERPT_CHARS = 240


def claim_label(verdict: str) -> str:
    return LABELS.get(str(verdict).upper(), "Unverified")


def excerpt(text: str, limit: int = EXCERPT_CHARS) -> str:
    """Short verbatim excerpt for display. Structured personal identifiers are masked; the stored document is untouched."""
    flat = redact_pii(re.sub(r"\s+", " ", text or "").strip())
    return flat if len(flat) <= limit else flat[:limit].rsplit(" ", 1)[0] + "…"


def retrieval_description(filename: str, chunks: list[dict], diagnostics: dict | None, assessment: dict | None,
                          actions: list[dict] | None) -> dict:
    diagnostics = diagnostics or {}
    hybrid = diagnostics.get("hybrid") or {}
    return {
        "scope": "selected case only",
        "source_file": filename,
        "method": "hybrid: semantic pgvector similarity + lexical BM25, fused by reciprocal rank, with an identifier-match rerank",
        "strategy": diagnostics.get("strategy"),
        "semantic_available": diagnostics.get("semantic_available", True),
        **({"degraded": "Semantic search was unavailable for this question; only keyword matching was used."}
           if diagnostics.get("semantic_available") is False else {}),
        "chunks_considered": len(chunks),
        "semantic_candidates": hybrid.get("semantic"),
        "lexical_candidates": hybrid.get("lexical"),
        "quality": (assessment or {}).get("quality"),
        "quality_signals": {k: (assessment or {}).get(k) for k in ("top_similarity", "term_coverage", "identifiers_ok")} if assessment else None,
        "corrective_actions": actions or [],
    }


def build_evidence_report(*, filename: str, chunks: list[dict], claim_verdicts: list[dict], removed_claims: list[str],
                          retrieval: dict, citations: dict | None, uncertainty_inputs: dict) -> dict:
    """uncertainty_inputs: weak_retrieval, pages_estimated, index_warning, judge_status, corrected, answer_quality."""
    # pages that back each claim, mapped to the retrieved chunks on that page
    backing: dict[int, list[int]] = {}
    for i, v in enumerate(claim_verdicts):
        if v.get("verdict") in ("SUPPORTED", "PARTIALLY_SUPPORTED"):
            for p in v.get("page_numbers") or []:
                backing.setdefault(p, []).append(i + 1)

    seen, evidence = set(), []
    for c in chunks:
        cid = str(c.get("id"))
        if cid in seen:
            continue
        seen.add(cid)
        page = c.get("page_number")
        evidence.append({
            "source": filename,
            "page": page,
            "page_estimated": bool(uncertainty_inputs.get("pages_estimated")) if page else None,
            "chunk_id": c.get("id"),
            "paragraphs": paragraph_numbers(c.get("chunk_text", "")),     # explicit markers in the text; may be empty
            "excerpt": excerpt(c.get("chunk_text", "")),
            "retrieved_by": c.get("retrieved_by") or ["semantic"],
            "similarity": round(c["similarity"], 3) if isinstance(c.get("similarity"), (int, float)) else None,
            "supports_claims": backing.get(page, []) if page else [],
        })
    # chunks that back a claim first, then by retrieval order
    evidence.sort(key=lambda e: (not e["supports_claims"],))

    claims = [{"n": i + 1, "claim": v.get("claim"), "label": claim_label(v.get("verdict")),
               "pages": v.get("page_numbers") or [], "reason": (v.get("reason") or "")[:240]}
              for i, v in enumerate(claim_verdicts)]
    conflicts = [c for c, v in zip(claims, claim_verdicts) if v.get("verdict") == "CONTRADICTED"]
    missing = [{"claim": c, "note": "no supporting passage was found; removed from the answer"} for c in removed_claims]
    missing += [{"claim": c["claim"], "note": "could not be verified against the retrieved passages"}
                for c, v in zip(claims, claim_verdicts) if v.get("verdict") == "NOT_VERIFIABLE"]

    uncertainty = []
    if uncertainty_inputs.get("weak_retrieval"):
        uncertainty.append("Retrieval quality was weak: the retrieved passages cover only part of the question.")
    if uncertainty_inputs.get("pages_estimated"):
        uncertainty.append("Page numbers for this document are approximate (the file had no reliable page boundaries).")
    if uncertainty_inputs.get("index_warning"):
        uncertainty.append(uncertainty_inputs["index_warning"])
    if uncertainty_inputs.get("judge_status") == "unavailable":
        uncertainty.append("Automated claim verification was not available, so no claim is marked verified.")
    if uncertainty_inputs.get("corrected"):
        uncertainty.append("Statements that could not be verified were removed from the draft answer.")
    quality = uncertainty_inputs.get("answer_quality") or {}
    if quality.get("should_abstain"):
        uncertainty.append("The reviewer judged the evidence too thin to answer this reliably.")
    if quality.get("completeness") is not None and quality["completeness"] <= 2:
        uncertainty.append("The answer may not cover everything the document says about this question.")
    for issue in (quality.get("issues") or [])[:3]:
        uncertainty.append(f"Reviewer note: {issue}")
    if citations and citations.get("not_backed"):
        uncertainty.append(f"Page(s) {citations['not_backed']} are cited in the answer, but no verified claim is attributed "
                           f"to them; check that the citation matches the statement.")
    if citations and citations.get("removed"):
        uncertainty.append(f"Page reference(s) {citations['removed']} were removed because they do not match any retrieved passage.")

    n_pages = sorted({e["page"] for e in evidence if e["page"]})
    where = (f"Retrieved from '{filename}' (the selected case) — {len(evidence)} passage(s)"
             + (f" on page(s) {', '.join(map(str, n_pages))}" if n_pages else "") + ".")
    return {
        "where_retrieved": where,
        "evidence": evidence,
        "claims": claims,
        "conflicting_evidence": conflicts,
        "missing_information": missing,
        "uncertainty": uncertainty,
        "retrieval": retrieval,
    }
